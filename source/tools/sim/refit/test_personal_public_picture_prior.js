'use strict';
const assert = require('assert/strict');
const { SYMBOLS, normalizedPrior, uniformPrior, hitProbability } = require('./personal_public_picture_prior.js');
const prior = uniformPrior(), counts = Array(256).fill(0);
assert.equal(SYMBOLS.length, 37); assert(Object.isFrozen(prior));
assert(Math.abs(prior.reduce((sum, value) => sum + value, 0) - 1) < 1e-12);
assert.equal(hitProbability(prior, [], counts), 0);
assert(Math.abs(hitProbability(prior, [1], counts) - 2 / 37) < 1e-12);
counts[1] = 1;
assert(Math.abs(hitProbability(prior, [], counts) - 2 / 37) < 1e-12);
counts[2] = 2;
assert(Math.abs(hitProbability(prior, [1, 1], counts) - 2 / 37) < 1e-12);
counts[2] = 1;
assert(Math.abs(hitProbability(prior, [1], counts) - 3 / 37) < 1e-12);
assert(Math.abs(hitProbability(prior, [101], counts) - 1) < 1e-12);
const weights = Array(256).fill(0); weights[1] = 1; weights[2] = 3;
const changed = normalizedPrior(weights); weights[1] = 99;
assert.equal(changed[1], .25); assert.equal(changed[2], .75);
assert.equal(hitProbability(changed, [1], Array(256).fill(0)), .25);
assert.throws(() => normalizedPrior(Array(256).fill(0)));
assert.throws(() => normalizedPrior(Array(256).fill(1)));
assert.throws(() => normalizedPrior([1]));
console.log('PASS public picture priors require no actual hidden faces, normalize only legal symbols and count public waiting/odd-known targets with wildcard semantics');
