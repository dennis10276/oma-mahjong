'use strict';
const assert = require('assert/strict');
const { tempered, temperSelector, temperedFactory } = require('./personal_tempered_choice.js');
assert.deepEqual(tempered([.25, .75], 1), [.25, .75]);
const sharper = tempered([.25, .75], .5), softer = tempered([.25, .75], 1.5);
assert(Math.abs(sharper[0] - .1) < 1e-12); assert(softer[0] > .25 && softer[0] < .5);
assert.deepEqual(tempered([0, 1, 0], .25), [0, 1, 0]);
assert(tempered([.8, .2], .25)[0] > .8);
for (const invalid of [0, .2, 3, NaN]) assert.throws(() => tempered([.5, .5], invalid));
assert.throws(() => tempered([0, 0], .5));
assert.throws(() => tempered([.5, -.5, 1], .5));
let delegated = 0;
const observations = [];
const base = (decision, draw) => { delegated++; const selected = draw < .25 ? 0 : 1; observations.push(selected); return selected; };
base.probabilities = decision => decision.values.slice();
base.observe = (decision, selected) => observations.push(selected);
base.posterior = () => observations.slice();
const zero = temperSelector(base, 1), modified = temperSelector(base, .5);
const decision = { values: [.25, .75], F: [{ knownMatch: true }, { knownMatch: false }], k: 0 };
assert.equal(zero(decision, .2), 0); assert.equal(delegated, 1);
assert.equal(modified(decision, .2), 1); assert.equal(delegated, 1);
assert.deepEqual(modified.posterior(), [0, 1]);
assert.deepEqual(modified.probabilities({ ...decision, k: 1, futureWinningAttempt: 9 }), sharper);
assert.equal(observations.length, 2);
assert.throws(() => modified(decision, 1));
assert.throws(() => temperedFactory({ id: 'Dennis', name: 'Dennis' }, { id: 'Gerda', name: 'Gerda' }, .5));
console.log('PASS personal temperature preserves ranking/zero support and exact baseline delegation; observes final choices without generic greedy matching');
