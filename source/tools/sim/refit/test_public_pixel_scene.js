'use strict';
const assert = require('assert/strict');
const { areaOf, TARGET_OPAQUE_INSET } = require('./public_pixel_scene.js');
assert.equal(TARGET_OPAQUE_INSET, 1.5);
const lower = { index: 0, alive: true, zIndex: 0, bounds: { left: 0, top: 0, right: 100, bottom: 124 } };
const upper = { index: 1, alive: true, zIndex: 1, bounds: { left: 4, top: 4, right: 104, bottom: 128 } };
for (const tile of [lower, upper]) Object.defineProperty(tile, 'face', { get() { throw Error('Private identity'); } });
const partial = areaOf({ tiles: [lower, upper] }, 0);
assert.equal(partial.mask[62 * 100 + 50], 0);
assert.equal(partial.mask[14 * 100 + 1], 0);
assert.equal(partial.mask[24 * 100 + 1], 1);
assert.equal(partial.mask[0], 0);
assert(partial.mask.some(Boolean));
const antialiasedSliver = areaOf({ tiles: [lower, { ...upper, bounds: { left: 2, top: 2, right: 102, bottom: 126 } }] }, 0);
assert(!antialiasedSliver.mask.some(Boolean));
const uncovered = areaOf({ tiles: [lower, { ...upper, alive: false }] }, 0);
assert.equal(uncovered.mask[62 * 100 + 50], 1);
const sameLayer = areaOf({ tiles: [lower, { ...upper, zIndex: 0 }] }, 0);
assert.deepEqual(sameLayer.mask, partial.mask);
const behind = areaOf({ tiles: [{ ...upper, zIndex: 0 }, lower] }, 0);
assert.deepEqual(behind.mask, uncovered.mask);
const observedForeground = areaOf({ tiles: [lower, upper] }, 0, new Set([1]));
assert.equal(observedForeground.mask[62 * 100 + 50], 0);
assert(observedForeground.mask.reduce((sum, value) => sum + value, 0) > partial.mask.reduce((sum, value) => sum + value, 0));
assert.throws(() => areaOf({ tiles: [lower, upper] }, 0, new Set([99])));
assert.throws(() => areaOf({ tiles: [lower, upper] }, 0, [1]));
assert.throws(() => areaOf({ tiles: [lower] }, 2));
const body = { ...lower, bounds: { left: 155.5, top: 25.6875, right: 289.390625, bottom: 192.078125 } };
const foreground = { ...upper, bounds: { left: 68.890625, top: 6.6875, right: 202.78125, bottom: 173.078125 } };
const throughBodyOnly = areaOf({ tiles: [body, foreground] }, 0);
const throughOpaqueDepth = areaOf({ tiles: [body, foreground], depth: '11.5px' }, 0);
const pixel = (166 - throughBodyOnly.rectangle.top) * throughBodyOnly.rectangle.width + 206 - throughBodyOnly.rectangle.left;
assert.equal(throughBodyOnly.mask[pixel], 1); assert.equal(throughOpaqueDepth.mask[pixel], 0);
assert.throws(() => areaOf({ tiles: [body], depth: 'bad' }, 0));
console.log('PASS sanitized scene masks exclude antialiased target borders with a fixed1.5-pixel opacity inset, use only public geometry/paint order, exclude foreground/depth and retain exposed edge pixels without private identities');
