'use strict';
const assert = require('assert/strict');
const { inventoryWorlds, solvePublicBelief } = require('./public_belief_exact.js');
const { verifyCertificate } = require('./public_belief_certificate.js');
const { verifyGrounding } = require('./public_belief_grounding.js');
const { verifySupport } = require('./public_belief_support.js');
const { physicalBound } = require('./public_belief_physical_bound.js');
const { evaluateReference } = require('./personal_public_belief_benchmark.js');
const { verifyReferencePaths } = require('./personal_public_belief_verify.js');
const problemOf = (inventory, down = inventory.map(() => 0), changes = {}) => ({
  tiles: inventory.map((unused, index) => ({ x: index * 8, y: 0, z: 0 })), down,
  belief: { kind: 'declared-public-inventory-uniform-v1', inventory }, ...changes });

const pair = solvePublicBelief(problemOf([1, 1], [1, 1]));
assert.equal(pair.status, 'exact'); assert.equal(pair.winningWorlds, 1); verifyCertificate(pair);
const odd = solvePublicBelief(problemOf([1, 2], [1, 1]));
assert.equal(odd.winningWorlds, 0); assert.equal(odd.totalWorlds, 2); verifyCertificate(odd);
assert(odd.inspectionCycleComponents > 0);
assert.equal(physicalBound(odd).physicallyUnclearableWorlds, 2);
assert(odd.nodes.some(node => node.public.state.arriving.length > 0));
const clock = solvePublicBelief(problemOf([1, 1], [0, 0], { clock: { i: 1, n: 1 } }));
const root = clock.nodes[clock.roots[0]];
assert.equal(root.policyIndex, 1); assert.equal(root.actions.find(action => action.index === 0).winningWorlds, 0);
assert.equal(root.actions.find(action => action.index === 1).winningWorlds, 1); verifyCertificate(clock);
assert.equal(verifyGrounding(clock).groundedWorldActionBranches, 3);
const fabricated = structuredClone(clock), fabricatedRoot = fabricated.nodes[fabricated.roots[0]];
const winningChild = fabricatedRoot.actions.find(action => action.index === 1).children;
fabricatedRoot.actions.find(action => action.index === 0).children = winningChild.slice();
fabricatedRoot.actions.find(action => action.index === 0).winningWorlds = 1;
verifyCertificate(fabricated);
assert.throws(() => verifyGrounding(fabricated), /AssertionError/);
const four = solvePublicBelief(problemOf([1, 1, 2, 2], [1, 1, 1, 1]));
assert.equal(four.status, 'exact'); assert.equal(four.winningWorlds, 6); assert.equal(four.totalWorlds, 6); verifyCertificate(four);
assert.equal(verifySupport(four).completeUniformHypotheses, 6);
assert.equal(physicalBound(four).physicallyClearableWorlds, 6);
const missing = structuredClone(four); missing.worlds.pop(); assert.throws(() => verifySupport(missing), /Incomplete/);
const repeated = structuredClone(four); repeated.worlds[1] = repeated.worlds[0].slice(); assert.throws(() => verifySupport(repeated), /Duplicate/);
const referencePaths = evaluateReference(four); verifyReferencePaths(four, referencePaths);
const changedPath = structuredClone(referencePaths); changedPath.rows[0].history[0] = 99;
assert.throws(() => verifyReferencePaths(four, changedPath), /AssertionError/);
const low = solvePublicBelief(problemOf([1, 1, 2, 2], [1, 1, 1, 1]), { maximumNodes: 2 });
assert.equal(low.status, 'unresolved'); assert.equal(low.winningWorlds, null);
assert.equal(solvePublicBelief(problemOf([1, 1, 2, 2]), { maximumWorlds: 2 }).reason, 'hypothesisBudget');
assert.equal(solvePublicBelief(problemOf([1, 1]), { maximumSimulatedTaps: 1 }).reason, 'productionReplayBudget');
assert.throws(() => solvePublicBelief({ ...problemOf([1, 1]), faces: [1, 1] }), /public synthetic problem/);
assert.throws(() => solvePublicBelief(problemOf([101, 101])), /Jokers/);
assert.throws(() => solvePublicBelief(problemOf([1, 1], [0, 0], { tiles: [{ x: 0, y: 0, z: 0 }, { x: 1, y: 0, z: 1 }] })), /observation contract/);
assert.throws(() => inventoryWorlds(problemOf([1, 1], [1, 1], { openingPictures: [1, null] }), 10), /initially visible/);
const swapped = problemOf([2, 1, 2, 1], [1, 1, 1, 1]);
Object.defineProperty(swapped, 'faces', { get() { throw Error('Private actual deck access'); } });
assert.deepEqual(inventoryWorlds(swapped, 10), four.worlds);
const inflated = structuredClone(clock); inflated.nodes[inflated.roots[0]].winningWorlds = 0;
assert.throws(() => verifyCertificate(inflated), /Bellman upper bound|attain/);
const cycle = structuredClone(pair), selected = cycle.nodes[cycle.roots[0]];
selected.rank = 0; assert.throws(() => verifyCertificate(cycle), /recurrent branch/);
console.log('PASS exact declared-belief policies use production actions, solve inspection cycles, certify rational optimal values independently, obey clock costs, reject hidden/Joker/partial-edge inputs and preserve numerical limits as unresolved');
