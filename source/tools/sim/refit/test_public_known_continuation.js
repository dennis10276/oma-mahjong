'use strict';
const assert = require('assert/strict'), Layouts = require('../../../www/layouts.js');
const { analyze, analyzeContinuation } = require('./public_dead_end.js');
const { analyzeRecovery } = require('./public_recovery_graph.js');
const { createSession } = require('./production_physical_session.js');
const tiles = [{ x: 0, y: 0, z: 1 }, { x: 0, y: 0, z: 0 }, { x: 8, y: 0, z: 0 }, { x: 16, y: 0, z: 0 }];
const game = { tiles, nb: Layouts.neighbors(tiles), rules: null, clock: { i: 0, n: 1 } };
Object.defineProperty(game, 'faces', { get() { throw Error('Private hidden face read'); } });
const state = { alive: [1, 1, 1, 1], pictures: [1, null, 2, 2], down: [1, 0, 1, 0],
  tray: [], moves: 0, openPeek: 0, relieved: false, arriving: [] };
const roots = [{ index: 2 }];
const inspection = analyze(game, state, roots, 64);
assert(!inspection.knownDead); assert.equal(inspection.reason, 'safeRemoval');
const report = analyzeContinuation(game, state, roots, 64);
assert(!report.knownDead); assert.equal(report.reason, 'reachableInformation');
assert.deepEqual(report.path.slice(0, 3), [2, 0, 0]);
const actual = createSession({ tiles, nb: game.nb, faces: [1, 1, 2, 2], down: [1, 0, 1, 0], rules: null, clock: game.clock });
for (const index of [2, 0, ...report.path.slice(0, -1)]) actual.tap(index);
assert.equal(actual.view().state.alive[0], 0); assert.equal(actual.view().state.moves, 1);
assert(actual.view().legalTiles.includes(1));
const flat = { tiles: tiles.map((tile, index) => ({ x: index * 8, y: 0, z: 0 })), rules: null, clock: null };
flat.nb = Layouts.neighbors(flat.tiles);
const trapped = { ...state, pictures: [null, null, null, 4], alive: [0, 0, 0, 1], down: [0, 0, 0, 0], tray: [1, 2, 3], openPeek: -1 };
const dead = analyzeContinuation(flat, trapped, [{ index: 3 }], 64);
assert(dead.knownDead && dead.certificate.includesSafeRemovalsAndInspections);
const independent = analyzeRecovery(flat, trapped, { nodes: 64 }); assert(independent.complete && !independent.knownWinningRoute);
const known = { ...state, pictures: [1, 1, 2, 2], down: [0, 0, 0, 0], openPeek: -1 };
const won = analyzeContinuation(flat, known, [0, 1, 2, 3].map(index => ({ index })), 64);
assert.equal(won.reason, 'knownWin'); assert(!won.knownDead);
assert.equal(analyzeContinuation(flat, known, [{ index: 0 }], 1).reason, 'bounded');
assert(!analyzeContinuation(flat, { ...known, pictures: [null, 1, 2, 2] }, [{ index: 0 }], 64).knownDead);
assert.throws(() => analyzeContinuation(flat, known, [{ index: 0 }], 0));
console.log('PASS known-continuation proofs include safe removals, preserve initial root restrictions only on the first tap, reopen returned states fully, and never turn unknowns or bounds into losses');
