'use strict';
const assert = require('assert/strict');
const L = require('../../../www/layouts.js');
const { FEATURES, featuresOf, exitOf } = require('./known_clock_strategy.js');
const tiles = [0, 4, 8, 12].map(coordinate => ({ x: coordinate, y: 0, z: 0 }));
const game = { tiles, nb: L.neighbors(tiles), rules: null, clock: { i: 0, n: 4 } };
const state = { alive: [1, 1, 1, 1], pictures: [0, 1, 2, 3], down: [0, 0, 0, 0],
  tray: [1, 2, 4], moves: 0, openPeek: -1, relieved: false, arriving: [] };
const actions = [0, 1, 2, 3].map(index => ({ index }));
const result = featuresOf(game, state, actions);
assert.equal(FEATURES.length, 12);
assert.equal(result.features[0][4], 1);
assert.equal(result.features[1][1], 1);
assert.equal(result.features[1][6], 1);
assert.equal(result.features[2][1], 1);
const noTime = featuresOf({ ...game, clock: { i: 0, n: 1 } }, state, actions);
assert.equal(noTime.features[1][4], 1);
const postExit = { ...state, alive: [0, 1, 1, 1] };
assert.equal(exitOf(game, postExit).threeMatch, true);
assert.equal(exitOf(game, { ...postExit, pictures: [0, null, null, 3] }).threeMatch, false);
assert.equal(exitOf(game, { ...postExit, tray: [2, 4] }).two, true);
assert.deepEqual(featuresOf(game, { ...state, pictures: [0, null, 2, 3], down: [0, 1, 0, 0] }, actions).features[1].slice(0, 6), [0, 0, 0, 0, 0, 1]);
assert.deepEqual(featuresOf(game, state, actions.slice().reverse()).features, result.features.slice().reverse());
assert.deepEqual(featuresOf({ ...game, clock: null }, state, actions).features, actions.map(() => FEATURES.map(() => 0)));
assert.equal(featuresOf(game, state, actions, { taps: 1, nodes: 256 }).features[1][11], 1);
assert.equal(featuresOf(game, state, actions, { taps: 1, nodes: 256 }).features[1][4], 0);
assert.deepEqual(featuresOf({ ...game, faces: [99, 98, 97, 96] }, state, actions), result);
const twinTiles = [0, 2, 6].map(coordinate => ({ x: coordinate, y: 0, z: 0 }));
const twinGame = { ...game, tiles: twinTiles, nb: L.neighbors(twinTiles) };
const twinState = { ...state, alive: [1, 1, 1], pictures: [0, 0, 3], down: [1, 1, 0], openPeek: 1 };
const atomic = featuresOf(twinGame, twinState, [{ index: 0 }]).features[0];
assert.equal(atomic[7], 0.5);
assert.equal(atomic[10], 1);
assert(atomic.every(value => value >= 0 && value <= 1));
console.log('PASS clock strategy distinguishes pair-first within budget, two-slot exits, ready tray matches and unresolved public probes');
