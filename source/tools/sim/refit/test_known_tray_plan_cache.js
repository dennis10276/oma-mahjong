'use strict';
const assert = require('assert/strict');
const L = require('../../../www/layouts.js');
const { featuresOf } = require('./known_tray_plan.js');
const { planningCache } = require('./known_tray_plan_cache.js');
const parameters = { taps: 6, nodes: 256, progress: 4 };
const tiles = [0, 0, 1, 1].map((face, index) => ({ x: index * 4, y: 0, z: 0 }));
const game = { tiles, nb: L.neighbors(tiles), rules: null, clock: null };
const state = { alive: [1, 1, 1, 1], pictures: [0, 0, 1, 1], down: [0, 0, 0, 0], tray: [], moves: 0,
  openPeek: -1, relieved: false, arriving: [] };
const actions = [{ index: 0 }, { index: 1 }, { index: 2 }, { index: 3 }];
const plan = planningCache(parameters, 2);
const first = plan(game, state, actions), expected = featuresOf(game, state, actions, parameters);
assert.deepEqual(first, expected);
first.features[0][0] = 99;
const cached = plan({ ...game }, { ...state }, actions);
assert.equal(cached.cacheHit, true);
assert.equal(cached.nodes, 0);
assert.deepEqual(cached.features, expected.features);
assert.equal(cached.boundaries, expected.boundaries);
cached.features[0][0] = 77;
assert.deepEqual(plan(game, state, actions).features, expected.features);
const reordered = [actions[2], actions[0], actions[3], actions[1]];
assert.deepEqual(plan(game, state, reordered).features, featuresOf(game, state, reordered, parameters).features);
const hidden = { ...state, pictures: [null, 0, 1, 1], down: [1, 0, 0, 0] };
assert.deepEqual(plan(game, hidden, actions).features, featuresOf(game, hidden, actions, parameters).features);
assert.equal(plan.stats().size, 2);
assert.equal(plan.stats().hits, 2);
const clock = { ...game, clock: { i: 3, n: 1 } };
assert.deepEqual(plan(clock, state, actions).features, featuresOf(clock, state, actions, parameters).features);
assert.equal(plan(clock, state, actions).cacheHit, true);
const changedRules = { ...game, rules: { ice: {}, iceNb: [], locks: new Set([0]), keys: [2, 3] } };
const changedActions = [{ index: 1 }, { index: 2 }, { index: 3 }];
assert.deepEqual(plan(changedRules, state, changedActions).features, featuresOf(changedRules, state, changedActions, parameters).features);
assert.throws(() => planningCache(parameters, 0), /Invalid/);
const mutable = { ...game }, mutablePlan = planningCache(parameters);
mutablePlan(mutable, state, actions);
mutable.clock = { i: 3, n: 1 };
assert.deepEqual(mutablePlan(mutable, state, actions).features, featuresOf(mutable, state, actions, parameters).features);
mutable.clock = null;
assert.deepEqual(mutablePlan(mutable, state, actions).features, expected.features);
console.log('PASS bounded planning cache keys only public state and candidate order, isolates boards/knowledge and never shares mutable feature arrays');
