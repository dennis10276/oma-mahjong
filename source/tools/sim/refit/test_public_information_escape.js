'use strict';
const assert = require('assert/strict'), Layouts = require('../../../www/layouts.js');
const { search, REFERENCE_PARAMETERS } = require('./public_witness_search.js');
const { describeKnownPath, guardedSearch } = require('./public_witness_reopen_guard.js');
const { decodeGeometry } = require('./personal_reference_failure_trace.js');
const fixture = require('./fixtures/reference-known-information.json'), game = decodeGeometry(fixture.geometry);
Object.defineProperty(game, 'faces', { get() { throw Error('Private actual faces read'); } });
const legacy = search(game, fixture.state, fixture.actions, { ...REFERENCE_PARAMETERS, continuationPruning: true });
assert.equal(legacy.index, fixture.legacyRoot); assert.equal(describeKnownPath(game, fixture.state, legacy.path).finalTray, 3);
const candidate = search(game, fixture.state, fixture.actions, { ...REFERENCE_PARAMETERS, continuationPruning: true, safeInformationEscape: true });
assert.notEqual(candidate.index, legacy.index); assert(candidate.information && candidate.knownProgress > 0);
const safety = describeKnownPath(game, fixture.state, candidate.path);
assert(safety.safe && safety.finalTray <= 2); assert(candidate.nodes <= REFERENCE_PARAMETERS.nodes);
assert(candidate.reopenAudit.safeInformation.eligible && candidate.reopenAudit.safeInformation.selected);
const tiles = [0, 1].map(index => ({ x: index * 8, y: 0, z: 0 })), flat = { tiles, nb: Layouts.neighbors(tiles), rules: null, clock: null };
const state = { alive: [1, 1], pictures: [null, 1], down: [1, 0], tray: [2, 3], moves: 0, openPeek: -1, relieved: false, arriving: [] };
assert(describeKnownPath(flat, state, [0]).safe); assert(!describeKnownPath(flat, state, [0, 1]).safe);
const winning = { index: 1, path: [1], knownWin: true, safeClockExit: false, nodes: 1 };
let calls = 0;
const guard = guardedSearch(() => { calls++; return winning; });
assert.deepEqual(guard(flat, state, [{ index: 0, inspect: true }, { index: 1 }], { safeInformationEscape: true }), winning);
assert.equal(calls, 1);
assert.throws(() => search(game, fixture.state, fixture.actions, { ...REFERENCE_PARAMETERS, safeInformationEscape: 'yes' }));
console.log('PASS optional information escape preserves known wins and clock priorities, rejects hypothetical suffixes after unknowns, shares the original search budget and prefers a verified lower-pressure public frontier over a crowded commitment');
