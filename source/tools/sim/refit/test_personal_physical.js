'use strict';
const assert = require('assert/strict');
const Hard = require('../../../www/hard.js'), L = require('../../../www/layouts.js');
const persona = { ...Hard.P, physicalFlips: true, peek: 0, end: 0, plan: 0, flips: true, allMoves: true, forceMatches: false };
const boardOf = (faces, down = faces.map(() => 0)) => {
  const tiles = faces.map((face, index) => ({ x: index * 4, y: 0, z: 0 }));
  return { tiles, nb: L.neighbors(tiles), faces, down, log: [], policyLog: [], logMatches: true };
};
const first = { ...boardOf([0, 0, 1, 1], [0, 1, 0, 0]), start: [0], follow: [-2] };
const firstResult = Hard.play(first, persona, 1);
assert.equal(firstResult.moves, 2);
assert.equal(firstResult.at[1], 1);
assert.deepEqual(firstResult.tray, []);
assert.equal(first.policyLog.length, 1);
assert.equal(first.policyLog[0].F[first.policyLog[0].k][19], 1);
const twins = { ...boardOf([0, 0, 1, 1], [1, 1, 0, 0]), follow: [-1, -2] };
const twinResult = Hard.play(twins, persona, 1);
assert.equal(twinResult.moves, 2);
assert.equal(twinResult.openPeek, -1);
assert.equal(twinResult.at[0], 1);
assert.equal(twinResult.at[1], 0);
assert.equal(twins.policyLog.length, 2);
const reopen = { ...boardOf([0, 0, 1, 1], [1, 1, 1, 1]), follow: [-1, -3, -1] };
const reopened = Hard.play(reopen, persona, 1);
assert.equal(reopened.moves, 0);
assert.equal(reopened.openPeek, 0);
assert.equal(reopen.policyLog.length, 3);
const last = reopen.policyLog[2];
assert.equal(last.F[last.k][Hard.POLICY_FEAT.indexOf('knownReopen')], 1);
assert.equal(last.F[last.k][Hard.POLICY_FEAT.indexOf('picture0')], 1);
const full = { ...boardOf([0, 1, 2, 0, 1, 3, 3, 2], [0, 0, 0, 0, 0, 1, 0, 0]), start: [0, 1, 2], openPeekAtStart: 5, follow: [6] };
const fullResult = Hard.play(full, persona, 1);
assert.equal(fullResult.moves, 5);
assert.equal(fullResult.tray.length, 3);
assert.equal(fullResult.at[5], 4);
assert.equal(fullResult.at[6], 3);
const fullDecision = full.policyLog[0];
assert.equal(fullDecision.F[fullDecision.k][14], 1);
assert.equal(fullDecision.F[fullDecision.k][18], 0);
assert.equal(fullDecision.F[fullDecision.k][Hard.POLICY_FEAT.indexOf('visiblePeekMatch')], 1);
const clock = { ...boardOf([0, 0, 1, 1], [0, 1, 0, 0]), openPeekAtStart: 1, clock: { i: 1, n: 1 }, follow: [0] };
const clockResult = Hard.play(clock, persona, 1);
assert.equal(clockResult.moves, 2);
assert.equal(clockResult.why, 'stopped');
assert.equal(clockResult.at[1], 1);
const arriving = { ...boardOf([101, 0, 0, 1, 1, 101]), follow: [0, 1], tapTimes: [100, 127], physicalLog: [] };
const arrivingResult = Hard.play(arriving, persona, 1);
assert.deepEqual(arrivingResult.tray, [101, 0]);
assert.equal(arrivingResult.moves, 2);
const settled = { ...boardOf([101, 0, 0, 1, 1, 101]), follow: [0, 1], tapTimes: [100, 400] };
const settledResult = Hard.play(settled, persona, 1);
assert.deepEqual(settledResult.tray, []);
assert.equal(settledResult.moves, 3);
const futureTiming = [[100, 127], [100, 400]].map(tapTimes => {
  const game = { ...boardOf([101, 0, 0, 1, 1, 101]), follow: [0, 1], tapTimes };
  Hard.play(game, persona, 1);
  return game.policyLog[0].F;
});
assert.deepEqual(futureTiming[0], futureTiming[1]);
const hiddenFeatures = [[0, 0, 1, 1], [0, 1, 1, 0]].map(faces => {
  const hidden = { ...boardOf(faces, [0, 1, 0, 1]), start: [0], follow: [-2] };
  Hard.play(hidden, persona, 1);
  return hidden.policyLog[0];
});
assert.deepEqual(hiddenFeatures[0].F, hiddenFeatures[1].F);
assert.deepEqual(hiddenFeatures[0].kindContext, hiddenFeatures[1].kindContext);
const fatal = { ...boardOf([0, 1, 2, 0, 1, 2, 3, 3]), start: [0, 1, 2] };
const fatalResult = Hard.play(fatal, { ...persona, kinds: { 't3n-': { fatal: 1 } } }, 1);
assert.equal(fatalResult.moves, 4);
assert.equal(fatalResult.why, 'tray');
assert.equal(fatalResult.tray.length, 4);
const trace = [];
const bounded = Hard.play({ ...boardOf([0, 0, 1, 1], [1, 1, 1, 1]), memory: [1, 1, 1, 1] },
  { ...persona, kinds: { t0n: { flip: 1 } } }, 1, trace);
assert(bounded.moves > 0);
assert(trace.length < 200);
assert.throws(() => Hard.play(boardOf([0, 0]), { ...persona, peek: 1 }), /Physical-tap actors/);
assert.throws(() => Hard.play(boardOf([0, 0]), { ...persona, end: 12 }), /Physical-tap actors/);
console.log('PASS physical taps: mandatory tray/open-twin matches, one peek, known reopens, full tray, clock atomicity and hidden-picture invariance');
