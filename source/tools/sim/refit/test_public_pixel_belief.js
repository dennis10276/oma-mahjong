'use strict';
const assert = require('assert/strict');
const { condition, symbolCompatibility } = require('./public_pixel_belief.js');
const { normalizedPrior } = require('./personal_public_picture_prior.js');
const prior = Array.from(normalizedPrior(Array.from({ length: 256 }, (unused, picture) => picture === 1 ? .6 : picture === 2 ? .3 : picture === 3 ? .1 : 0)));
const ambiguous = { type: 'publicPixelPartition-v1', pictures: [1, 2], known: null, visiblePixels: 1, reason: 'ambiguousPixels' };
const belief = condition(prior, ambiguous);
assert(belief.conditioned && !belief.zeroMassFallback);
assert(Math.abs(belief.weights[1] - 2 / 3) < 1e-12); assert(Math.abs(belief.weights[2] - 1 / 3) < 1e-12);
assert.equal(belief.weights[3], 0);
const identified = condition(prior, { ...ambiguous, pictures: [3], known: 3, reason: 'identified' });
assert.equal(identified.weights[3], 1);
const mismatch = condition(prior, { ...ambiguous, pictures: [1], reason: 'outsideDictionary' });
assert.deepEqual(mismatch.weights, prior); assert(!mismatch.conditioned);
const noPixels = condition(prior, { ...ambiguous, visiblePixels: 0, reason: 'noSafeVisiblePixels' });
assert.deepEqual(noPixels.weights, prior);
const zeroMass = condition(prior, { ...ambiguous, pictures: [4, 5] });
assert(zeroMass.zeroMassFallback); assert.equal(zeroMass.weights[4], .5); assert.equal(zeroMass.weights[5], .5);
const joker = Array(256).fill(0); joker[101] = 1;
assert.equal(symbolCompatibility(joker, identified.weights), 1);
assert(Math.abs(symbolCompatibility(belief.weights, belief.weights) - 5 / 9) < 1e-12);
assert.throws(() => condition(prior, { ...ambiguous, known: 1 }));
assert.throws(() => condition(prior, { ...ambiguous, pictures: [1, 1] }));
console.log('PASS public pixel beliefs condition only on observed symbol classes, keep uncertainty and mismatches explicit, and distinguish symbol compatibility from physical guarantees');
